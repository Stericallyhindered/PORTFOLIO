    public static IReadOnlyList<XdfTableDefinition> Classify(IReadOnlyList<XdfTableDefinition> source)
    {
        var axisOwners = BuildAxisOwners(source);
        var addressGroups = source
            .Where(table => table.ZAxis.Address.HasValue)
            .GroupBy(table => table.ZAxis.Address!.Value)
            .ToDictionary(group => group.Key, group => group.OrderBy(table => table.SourceIndex).ToArray());

        var classified = new XdfTableDefinition[source.Count];
        for (var index = 0; index < source.Count; index++)
        {
            var table = source[index];
            var evidence = new List<string>();
            var parents = table.ZAxis.Address.HasValue && axisOwners.TryGetValue(table.ZAxis.Address.Value, out var owners)
                ? owners.Select(owner => owner.Table.Id).Distinct(StringComparer.Ordinal).ToArray()
                : Array.Empty<string>();
            var addressGroup = table.ZAxis.Address.HasValue && addressGroups.TryGetValue(table.ZAxis.Address.Value, out var foundGroup)
                ? foundGroup
                : Array.Empty<XdfTableDefinition>();
            var aliases = addressGroup
                .Where(candidate => candidate.Id != table.Id)
                .Select(candidate => candidate.Id)
                .ToArray();

            var role = parents.Length > 0 || AutoGeneratedAxisTitle().IsMatch(table.Title)
                ? XdfTableRole.BreakpointAxis
                : aliases.Length > 0 && addressGroup[0].Id != table.Id
                    ? XdfTableRole.DuplicateAlias
                    : XdfTableRole.Calibration;
            if (parents.Length > 0) evidence.Add($"Binary address is used by {parents.Length} parent map axis definition(s).");
            if (aliases.Length > 0) evidence.Add($"Binary address is shared by {aliases.Length} other definition(s).");

            var shape = table.RowCount > 1 && table.ColumnCount > 1
                ? XdfTableShape.Map
                : table.RowCount * table.ColumnCount == 1
                    ? XdfTableShape.Scalar
                    : XdfTableShape.Curve;
            evidence.Add($"Dimensions identify this item as a {shape.ToString().ToLowerInvariant()}.");

            var symbol = ExtractSymbol(table.Description);
            if (symbol is not null) evidence.Add($"ECU symbol extracted from the XDF description: {symbol}.");
            var (system, confidence, systemEvidence) = ClassifySystem(table, symbol);
            evidence.Add(systemEvidence);
            var displayTitle = BuildDisplayTitle(table, role, parents, source, axisOwners);
            var sourceClass = table.Flags switch
            {
                0x30 => "XDF 0x30 definition",
                0x0 => "XDF 0x0 definition",
                null when AutoGeneratedAxisTitle().IsMatch(table.Title) => "Generated axis definition",
                null => "Unflagged XDF definition",
                _ => $"XDF 0x{table.Flags:X} definition"
            };
            var searchParts = new[]
            {
                table.Title,
                displayTitle,
                table.Description,
                symbol,
                string.Join(' ', table.CategoryNames),
                system.ToString(),
                shape.ToString(),
                role.ToString(),
                sourceClass,
                table.ZAxis.Address.HasValue ? $"0x{table.ZAxis.Address.Value:X}" : null
            };
            var searchText = string.Join(' ', searchParts.Where(part => !string.IsNullOrWhiteSpace(part)));
            var sortKey = $"{(int)system:D3}|{(int)role:D2}|{displayTitle.ToUpperInvariant()}|{table.ZAxis.Address ?? long.MaxValue:D16}|{table.SourceIndex:D6}";

            classified[index] = table with
            {
                Identity = new XdfTableIdentity(
                    displayTitle,
                    symbol,
                    system,
                    shape,
                    role,
                    sourceClass,
                    confidence,
                    evidence,
                    parents,
                    aliases,
                    searchText,
                    sortKey)
            };
        }

        return classified;
    }

    public static XdfCalibrationSystem ClassifySystem(
        string title,
        string? description,
        IReadOnlyList<string> categoryNames,
        out double confidence,
        out string evidence)
    {
        var primaryProbe = string.Join(' ', new[] { title, description }
            .Where(value => !string.IsNullOrWhiteSpace(value))).ToLowerInvariant();
        var rules = SystemRules;
        foreach (var rule in rules)
        {
            if (!rule.Pattern.IsMatch(primaryProbe)) continue;
            confidence = rule.Confidence;
            evidence = $"Matched {rule.Label} terminology in the title, ECU symbol, or description.";
            return rule.System;
        }

        var categoryProbe = string.Join(' ', categoryNames).ToLowerInvariant();
        foreach (var rule in rules)
        {
            if (!rule.Pattern.IsMatch(categoryProbe)) continue;
            confidence = 0.68;
            evidence = $"Assigned from the original XDF category using {rule.Label} terminology.";
            return rule.System;
        }

        confidence = categoryNames.Count > 0 ? 0.45 : 0.2;
        evidence = categoryNames.Count > 0
            ? "No specialized system rule matched; original XDF categories are retained."
            : "No system terminology or category matched; review is required.";
        return XdfCalibrationSystem.Uncategorized;
    }

    public static XdfTableIdentity UnclassifiedIdentity(string title) => new(
        title,
        null,
        XdfCalibrationSystem.Uncategorized,
        XdfTableShape.Scalar,
        XdfTableRole.Calibration,
        "Unclassified",
        0,
        Array.Empty<string>(),
        Array.Empty<string>(),
        Array.Empty<string>(),
        title,
        title);

    private static Dictionary<long, AxisOwner[]> BuildAxisOwners(IReadOnlyList<XdfTableDefinition> source) =>
        source
            .SelectMany(table => new[]
            {
                table.XAxis.Address.HasValue ? new AxisOwner(table, "X", table.XAxis.Address.Value) : null,
                table.YAxis.Address.HasValue ? new AxisOwner(table, "Y", table.YAxis.Address.Value) : null
            })
            .Where(owner => owner is not null)
            .Cast<AxisOwner>()
            .GroupBy(owner => owner.Address)
            .ToDictionary(group => group.Key, group => group.ToArray());

    private static string BuildDisplayTitle(
        XdfTableDefinition table,
        XdfTableRole role,
        IReadOnlyList<string> parents,
        IReadOnlyList<XdfTableDefinition> source,
        IReadOnlyDictionary<long, AxisOwner[]> axisOwners)
    {
        if (role != XdfTableRole.BreakpointAxis || !table.ZAxis.Address.HasValue || parents.Count == 0)
        {
            return table.Title;
        }

        var owner = axisOwners[table.ZAxis.Address.Value]
            .OrderBy(candidate => candidate.Table.SourceIndex)
            .First();
        return $"{owner.Table.Title} - {owner.AxisId} axis breakpoint";
    }

    private static string? ExtractSymbol(string? description)
    {
        if (string.IsNullOrWhiteSpace(description)) return null;
        var firstLine = description.Trim().Split(new[] { '\r', '\n' }, StringSplitOptions.RemoveEmptyEntries)[0].Trim();
        var separator = firstLine.IndexOf(" - ", StringComparison.Ordinal);
        var candidate = separator > 0 ? firstLine[..separator].Trim() : firstLine;
        return Symbol().IsMatch(candidate) ? candidate : null;
    }

    private static (XdfCalibrationSystem System, double Confidence, string Evidence) ClassifySystem(
        XdfTableDefinition table,
        string? symbol)
    {
        var description = string.Join(' ', new[] { table.Description, symbol }.Where(value => !string.IsNullOrWhiteSpace(value)));
        var system = ClassifySystem(table.Title, description, table.CategoryNames, out var confidence, out var evidence);
        return (system, confidence, evidence);
    }

