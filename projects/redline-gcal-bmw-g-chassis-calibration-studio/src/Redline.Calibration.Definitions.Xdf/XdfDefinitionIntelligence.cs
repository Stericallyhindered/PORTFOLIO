    private static SystemRule Rule(XdfCalibrationSystem system, string pattern, string label) =>
        new(system, new Regex(pattern, RegexOptions.IgnoreCase | RegexOptions.CultureInvariant | RegexOptions.Compiled), 0.82, label);

    [GeneratedRegex(@" ([XY]) \(autogen\)$", RegexOptions.IgnoreCase | RegexOptions.CultureInvariant)]
    private static partial Regex AutoGeneratedAxisTitle();

    [GeneratedRegex(@"^[A-Za-z][A-Za-z0-9_.$:#-]{2,}$", RegexOptions.CultureInvariant)]
